export function cleanInterfaceCopy(value: string) {
  const exact = {
    "Орден аналитического пиздеца": "Орден аналитической стойкости",
    "Календарь горящих жоп": "Календарь горящих дедлайнов",
    "Одной хернёй меньше": "Минус одна проблема",
    "Пять жоп за один присест": "Пять пожаров за один присест",
    "Бэклог, соси": "Бэклог, отдыхай",
    "Я вам не Ванга, блядь": "Я вам не Ванга",
    ТЗ_final_ЕБАНЫЙ_ФИНАЛ: "ТЗ_final_точно_последний",
    "Каждую срань — под галочку": "Каждую мелочь — под галочку",
    "Толстой бы заебался": "Толстой бы устал",
    "Пиздецу присвоен заголовок": "Хаосу присвоен заголовок",
    "Жирным, чтоб дошло, блядь": "Жирным, чтобы заметили",
    "У жопы появилась дата": "У паники появилась дата",
    "Просрочено, зато охуенно": "Просрочено, зато отлично",
    "В работе всё. В ахуе я.": "В работе всё. В шоке я.",
    "Мур, сука": "Мур. Официально.",
    "Пиздец тот же, зато глаза не вытекают.":
      "Хаос тот же, зато глаза не устают.",
    "Созвон на пять минут? Пиздёж.": "Созвон на пять минут? Верится с трудом.",
    "Мяу. Бизнес опять насрал в требования.":
      "Мяу. Бизнес опять переписал требования.",
    "Мур. Теперь закрой эту херню.": "Мур. Теперь закрой эту задачу.",
    "Требования уточнили. Я охуела уточнённо.":
      "Требования уточнили. Удивилась повторно.",
    "«Там на пять минут».\nМяу, блядь, конечно.":
      "«Там на пять минут».\nМяу. Конечно.",
    "Мяу, блядь, конечно.": "Мяу. Конечно.",
    "Заслужила. Каким, блядь, трудом.":
      "Заслужила. Каким трудом — отдельная история.",
    "Одна херня закрыта. Несите следующую.":
      "Одна задача закрыта. Несите следующую.",
  };
  let text = String(value);
  for (const [source, clean] of Object.entries(exact))
    text = text.split(source).join(clean);
  const substitutions: [RegExp, string][] = [
    [/пиздёж/giu, "сказки"],
    [/пиздецу/giu, "хаосу"],
    [/пиздец/giu, "хаос"],
    [/заебался/giu, "устал"],
    [/[её]баный/giu, "последний"],
    [/охуела/giu, "удивилась"],
    [/охуенно/giu, "отлично"],
    [/в ахуе/giu, "в шоке"],
    [/херн[её]й/giu, "задачей"],
    [/херню/giu, "задачу"],
    [/херня/giu, "задача"],
    [/срань/giu, "мелочь"],
    [/насрал/giu, "добавил хаоса"],
    [/жопы/giu, "проблемы"],
    [/жоп/giu, "проблем"],
    [/(?<![А-Яа-яЁё])блядь(?![А-Яа-яЁё])/giu, ""],
    [/(?<![А-Яа-яЁё])сука(?![А-Яа-яЁё])/giu, ""],
  ];
  for (const [pattern, replacement] of substitutions)
    text = text.replace(pattern, replacement);
  return text
    .replace(/ {2,}/g, " ")
    .replace(/,\s*,/g, ",")
    .replace(/,\s*([.!?])/g, "$1")
    .replace(/\s+([.!?])/g, "$1");
}
